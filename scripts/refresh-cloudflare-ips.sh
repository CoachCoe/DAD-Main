#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
target="$root/deploy/nginx/conf/cloudflare/edge-ranges.conf"
usage() { printf '%s\n' 'Usage: scripts/refresh-cloudflare-ips.sh [--check]'; }
check=false
case "${1:-}" in
  "") ;;
  --check) check=true ;;
  -h | --help) usage; exit 0 ;;
  *) usage >&2; exit 2 ;;
esac

fetch() { curl -fsS --proto '=https' --tlsv1.2 --max-time 20 "https://www.cloudflare.com/$1"; }
v4="$(fetch ips-v4)"
v6="$(fetch ips-v6)"

# A truncated or rewritten response must not silently narrow or widen who may set the client address.
render() {
  local family="$1" pattern="$2" minimum="$3" list="$4" count=0 range
  while read -r range; do
    range="${range%$'\r'}"
    [[ -n "$range" ]] || continue
    if [[ ! "$range" =~ $pattern ]]; then
      printf 'Unexpected %s range from Cloudflare: %q\n' "$family" "$range" >&2
      exit 1
    fi
    printf 'set_real_ip_from %s;\n' "$range"
    count=$((count + 1))
  done <<< "$list"
  if ((count < minimum)); then
    printf 'Cloudflare returned only %d %s ranges; refusing to continue.\n' "$count" "$family" >&2
    exit 1
  fi
}

output="$(mktemp "$target.XXXXXX")"
trap 'rm -f -- "$output"' EXIT
{
  printf '%s\n' '# Generated by scripts/refresh-cloudflare-ips.sh from https://www.cloudflare.com/ips-v4' \
    '# and https://www.cloudflare.com/ips-v6. Do not edit by hand.'
  render IPv4 '^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$' 10 "$v4"
  render IPv6 '^[0-9a-f:]+/[0-9]{1,3}$' 5 "$v6"
} > "$output"

if cmp -s "$output" "$target"; then
  printf 'Cloudflare ranges are current: %s\n' "${target#"$root/"}"
elif [[ "$check" == true ]]; then
  diff -u "$target" "$output" >&2 || true
  printf 'Cloudflare ranges changed; run scripts/refresh-cloudflare-ips.sh and reload nginx.\n' >&2
  exit 1
else
  chmod 0644 "$output"
  mv -- "$output" "$target"
  printf 'Updated %s; reload nginx with ./scripts/deploy.sh reload-ingress.\n' "${target#"$root/"}"
fi
